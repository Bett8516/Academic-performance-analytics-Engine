-- Run in the Supabase SQL Editor. Each authenticated instructor can access only their own marks.
create table if not exists public.student_marks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade default auth.uid(),
  name text not null check (char_length(trim(name)) between 1 and 120),
  math integer not null check (math between 0 and 100),
  science integer not null check (science between 0 and 100),
  created_at timestamptz not null default now()
);

create index if not exists student_marks_user_id_created_at_idx
  on public.student_marks (user_id, created_at desc);

alter table public.student_marks enable row level security;
revoke all on table public.student_marks from anon, authenticated;
grant select, insert, update, delete on table public.student_marks to authenticated;
grant usage, select on sequence public.student_marks_id_seq to authenticated;

drop policy if exists "Instructors read their own student marks" on public.student_marks;
create policy "Instructors read their own student marks"
  on public.student_marks for select to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Instructors add their own student marks" on public.student_marks;
create policy "Instructors add their own student marks"
  on public.student_marks for insert to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "Instructors update their own student marks" on public.student_marks;
create policy "Instructors update their own student marks"
  on public.student_marks for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "Instructors delete their own student marks" on public.student_marks;
create policy "Instructors delete their own student marks"
  on public.student_marks for delete to authenticated
  using ((select auth.uid()) = user_id);
